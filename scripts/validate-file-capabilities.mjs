#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY_PATH = "src/shared/fileCapabilities.json";
const GENERATED_TS_PATH = "src/domain/documents/generatedFileCapabilities.ts";
const GENERATED_DB_TS_PATH = "src/data/db/generatedFileCapabilities.ts";
const GENERATED_RUST_PATH = "src-tauri/src/generated_file_capabilities.rs";
const GENERATED_DOC_PATH = "docs/generated/supported-formats.md";
const ALLOWED_RUNTIMES = new Set(["browser", "hybrid", "native"]);

function repoPath(relativePath) {
  return path.join(REPO_ROOT, relativePath);
}

function fail(message) {
  throw new Error(message);
}

function quoteTs(value) {
  return JSON.stringify(value);
}

function quoteRust(value) {
  return JSON.stringify(value);
}

function sqlQuote(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function rustRuntime(value) {
  return value[0].toUpperCase() + value.slice(1);
}

function formatBytes(bytes) {
  if (bytes % 1048576 === 0) {
    return `${bytes / 1048576} MiB`;
  }
  return `${bytes} bytes`;
}

function validateCapabilities(raw) {
  if (!Array.isArray(raw)) fail("Capability registry must be a JSON array.");
  if (raw.length === 0) fail("Capability registry must contain at least one entry.");

  const seen = new Set();
  const capabilities = raw.map((entry, index) => {
    if (!entry || typeof entry !== "object" || Array.isArray(entry)) {
      fail(`Entry ${index} must be an object.`);
    }

    const {
      extension,
      displayLabel,
      parserId,
      mimeHints,
      maxFileSizeBytes,
      ocr,
      parseRuntime,
      defaultEnabled,
    } = entry;

    if (typeof extension !== "string" || !/^[a-z0-9]+$/.test(extension)) {
      fail(`Entry ${index} has invalid extension; use lowercase without a dot.`);
    }
    if (seen.has(extension)) fail(`Duplicate extension: ${extension}`);
    seen.add(extension);

    if (typeof displayLabel !== "string" || displayLabel.trim() !== displayLabel || displayLabel === "") {
      fail(`Entry ${extension} has invalid displayLabel.`);
    }
    if (typeof parserId !== "string" || !/^[a-z0-9-]+$/.test(parserId)) {
      fail(`Entry ${extension} has invalid parserId.`);
    }
    if (!Array.isArray(mimeHints) || mimeHints.some((hint) => typeof hint !== "string" || hint.trim() !== hint)) {
      fail(`Entry ${extension} has invalid mimeHints.`);
    }
    if (new Set(mimeHints).size !== mimeHints.length) {
      fail(`Entry ${extension} has duplicate mimeHints.`);
    }
    if (!Number.isSafeInteger(maxFileSizeBytes) || maxFileSizeBytes <= 0) {
      fail(`Entry ${extension} has invalid maxFileSizeBytes.`);
    }
    if (!ocr || typeof ocr !== "object" || Array.isArray(ocr) || typeof ocr.supported !== "boolean") {
      fail(`Entry ${extension} has invalid ocr metadata.`);
    }
    if (ocr.supported) {
      if (typeof ocr.parserId !== "string" || !/^[a-z0-9-]+$/.test(ocr.parserId)) {
        fail(`Entry ${extension} has invalid OCR parserId.`);
      }
    } else if ("parserId" in ocr) {
      fail(`Entry ${extension} must not include ocr.parserId when OCR is unsupported.`);
    }
    if (!ALLOWED_RUNTIMES.has(parseRuntime)) {
      fail(`Entry ${extension} has invalid parseRuntime.`);
    }
    if (typeof defaultEnabled !== "boolean") {
      fail(`Entry ${extension} has invalid defaultEnabled.`);
    }

    return {
      extension,
      displayLabel,
      parserId,
      mimeHints,
      maxFileSizeBytes,
      ocr,
      parseRuntime,
      defaultEnabled,
    };
  });

  return capabilities;
}

function generateTs(capabilities) {
  const extensions = capabilities.filter((capability) => capability.defaultEnabled).map((capability) => capability.extension);
  const entries = capabilities
    .map((capability) => `  {
    extension: ${quoteTs(capability.extension)},
    displayLabel: ${quoteTs(capability.displayLabel)},
    parserId: ${quoteTs(capability.parserId)},
    mimeHints: [${capability.mimeHints.map(quoteTs).join(", ")}],
    maxFileSizeBytes: ${capability.maxFileSizeBytes},
    ocr: ${capability.ocr.supported ? `{ supported: true, parserId: ${quoteTs(capability.ocr.parserId)} }` : "{ supported: false }"},
    parseRuntime: ${quoteTs(capability.parseRuntime)},
    defaultEnabled: ${capability.defaultEnabled},
  }`)
    .join(",\n");
  const filters = capabilities
    .filter((capability) => capability.defaultEnabled)
    .map((capability) => `  { value: ${quoteTs(capability.extension)}, label: ${quoteTs(capability.displayLabel)} }`)
    .join(",\n");

  return `// Generated by scripts/validate-file-capabilities.mjs. Do not edit by hand.

export type ParseRuntime = "browser" | "hybrid" | "native";

export interface FileCapability {
  extension: FileExtension;
  displayLabel: string;
  parserId: string;
  mimeHints: readonly string[];
  maxFileSizeBytes: number;
  ocr: { supported: false } | { supported: true; parserId: string };
  parseRuntime: ParseRuntime;
  defaultEnabled: boolean;
}

export const SUPPORTED_FILE_CAPABILITIES = [
${entries},
] as const satisfies readonly FileCapability[];

export const SUPPORTED_FILE_EXTENSIONS = [${extensions.map(quoteTs).join(", ")}] as const;

export type FileExtension = (typeof SUPPORTED_FILE_EXTENSIONS)[number];

export function isSupportedFileExtension(value: string): value is FileExtension {
  return (SUPPORTED_FILE_EXTENSIONS as readonly string[]).includes(value.toLowerCase());
}

function normalizeExtension(value: string): string {
  const trimmed = value.trim().toLowerCase();
  return trimmed.startsWith(".") ? trimmed.slice(1) : trimmed;
}

export function getFileCapability(value: string): FileCapability | null {
  const extension = normalizeExtension(value);
  return SUPPORTED_FILE_CAPABILITIES.find((capability) => capability.defaultEnabled && capability.extension === extension) ?? null;
}

export const FILE_EXTENSION_FILTER_OPTIONS = [
${filters},
] as const;
`;
}

function generateDbTs(capabilities) {
  const extensions = capabilities.filter((capability) => capability.defaultEnabled).map((capability) => capability.extension);
  const sqlList = extensions.map(sqlQuote).join(", ");
  return `// Generated by scripts/validate-file-capabilities.mjs. Do not edit by hand.

export const GENERATED_FILE_EXTENSIONS = [${extensions.map(quoteTs).join(", ")}] as const;

export const FILE_EXTENSION_SQL_LIST = ${quoteTs(sqlList)};

export const FILE_EXTENSION_CHECK_SQL = ${quoteTs(`file_extension IN (${sqlList})`)};

export const FILE_EXTENSION_DELETE_UNSUPPORTED_SQL =
  ${quoteTs(`file_extension NOT IN (${sqlList})`)};
`;
}

function generateRust(capabilities) {
  const extensions = capabilities.filter((capability) => capability.defaultEnabled).map((capability) => capability.extension);
  const entries = capabilities
    .map((capability) => `    FileCapability {
        extension: ${quoteRust(capability.extension)},
        display_label: ${quoteRust(capability.displayLabel)},
        parser_id: ${quoteRust(capability.parserId)},
        mime_hints: &[${capability.mimeHints.map(quoteRust).join(", ")}],
        max_file_size_bytes: ${capability.maxFileSizeBytes.toLocaleString("en-US").replaceAll(",", "_")},
        ocr_parser_id: ${capability.ocr.supported ? `Some(${quoteRust(capability.ocr.parserId)})` : "None"},
        parse_runtime: ParseRuntime::${rustRuntime(capability.parseRuntime)},
        default_enabled: ${capability.defaultEnabled},
    }`)
    .join(",\n");

  return `// Generated by scripts/validate-file-capabilities.mjs. Do not edit by hand.

use std::path::Path;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ParseRuntime {
    Browser,
    Hybrid,
    Native,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct FileCapability {
    pub extension: &'static str,
    pub display_label: &'static str,
    pub parser_id: &'static str,
    pub mime_hints: &'static [&'static str],
    pub max_file_size_bytes: u64,
    pub ocr_parser_id: Option<&'static str>,
    pub parse_runtime: ParseRuntime,
    pub default_enabled: bool,
}

pub const SUPPORTED_FILE_CAPABILITIES: &[FileCapability] = &[
${entries},
];

pub const SUPPORTED_FILE_EXTENSIONS: &[&str] = &[${extensions.map(quoteRust).join(", ")}];

pub fn supported_extension(path: &Path) -> Option<&'static str> {
    let extension = path.extension()?.to_str()?.to_ascii_lowercase();
    SUPPORTED_FILE_EXTENSIONS
        .iter()
        .copied()
        .find(|supported| *supported == extension)
}

pub fn capability_for_extension(extension: &str) -> Option<&'static FileCapability> {
    let normalized = extension
        .trim()
        .trim_start_matches('.')
        .to_ascii_lowercase();
    SUPPORTED_FILE_CAPABILITIES
        .iter()
        .find(|capability| capability.default_enabled && capability.extension == normalized)
}

pub fn capability_for_path(path: &Path) -> Option<&'static FileCapability> {
    let extension = path.extension()?.to_str()?;
    capability_for_extension(extension)
}

pub fn path_supports_parser(path: &Path, parser_id: &str) -> bool {
    capability_for_path(path)
        .map(|capability| capability.parser_id == parser_id)
        .unwrap_or(false)
}

pub fn path_supports_ocr_parser(path: &Path, parser_id: &str) -> bool {
    capability_for_path(path)
        .and_then(|capability| capability.ocr_parser_id)
        .map(|ocr_parser_id| ocr_parser_id == parser_id)
        .unwrap_or(false)
}
`;
}

function generateDoc(capabilities) {
  const rows = capabilities
    .filter((capability) => capability.defaultEnabled)
    .map((capability) => {
      const ocr = capability.ocr.supported ? `\`${capability.ocr.parserId}\`` : "No";
      return `| \`.${capability.extension}\` | ${capability.displayLabel} | \`${capability.parserId}\` | ${capability.parseRuntime} | ${ocr} | ${formatBytes(capability.maxFileSizeBytes)} |`;
    })
    .join("\n");

  return `<!-- Generated by scripts/validate-file-capabilities.mjs. Do not edit by hand. -->

# Supported Formats

StackDrop currently indexes these enabled file types:

| Extension | Label | Parser | Runtime | OCR | Max file size |
|-----------|-------|--------|---------|-----|---------------|
${rows}

Deferred Tier 1 and Tier 2 formats are intentionally absent until their full ingestion, parser, diagnostics, UI, test, and documentation slices are implemented.
`;
}

async function readRegistry() {
  const text = await readFile(repoPath(REGISTRY_PATH), "utf8");
  return validateCapabilities(JSON.parse(text));
}

function normalize(text) {
  return text.replace(/\r\n/g, "\n");
}

async function writeGenerated(files) {
  for (const [relativePath, content] of Object.entries(files)) {
    const absolutePath = repoPath(relativePath);
    await mkdir(path.dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, content, "utf8");
  }
}

async function checkGenerated(files) {
  const stale = [];
  for (const [relativePath, expected] of Object.entries(files)) {
    let actual = "";
    try {
      actual = await readFile(repoPath(relativePath), "utf8");
    } catch {
      stale.push(`${relativePath} is missing`);
      continue;
    }
    if (normalize(actual) !== normalize(expected)) {
      stale.push(`${relativePath} is stale`);
    }
  }
  if (stale.length > 0) {
    fail(`File capability artifacts are out of date:\n- ${stale.join("\n- ")}\nRun: node scripts/validate-file-capabilities.mjs --write`);
  }
}

async function main() {
  const mode = process.argv[2];
  if (mode !== "--check" && mode !== "--write") {
    fail("Usage: node scripts/validate-file-capabilities.mjs --check|--write");
  }

  const capabilities = await readRegistry();
  const files = {
    [GENERATED_TS_PATH]: generateTs(capabilities),
    [GENERATED_DB_TS_PATH]: generateDbTs(capabilities),
    [GENERATED_RUST_PATH]: generateRust(capabilities),
    [GENERATED_DOC_PATH]: generateDoc(capabilities),
  };

  if (mode === "--write") {
    await writeGenerated(files);
    console.log(`Wrote ${Object.keys(files).length} file capability artifacts.`);
    return;
  }

  await checkGenerated(files);
  console.log(`Validated ${capabilities.length} file capabilities and ${Object.keys(files).length} generated artifacts.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
